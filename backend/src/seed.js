async function seedData() {
  try {
    await connectDB();

    console.log('[Seed] Clearing existing collections (Banner, Category, Industry, Product, DownloadResource)...');
    await Banner.deleteMany({});
    await Category.deleteMany({});
    await Industry.deleteMany({});
    await Product.deleteMany({});
    await DownloadResource.deleteMany({});

    console.log('[Seed] Inserting Banners...');
    await Banner.insertMany(initialBanners);

    console.log('[Seed] Inserting Categories...');
    await Category.insertMany(initialCategories);

    console.log('[Seed] Inserting Industries...');
    await Industry.insertMany(initialIndustries);

    console.log('[Seed] Inserting Download Resources...');
    await DownloadResource.insertMany(initialDownloads);

    console.log('[Seed] Inserting Products with rich specifications, chemical composition & tech spec rows...');
    await Product.insertMany(initialProducts);

    // Update real-time product counts on categories
    console.log('[Seed] Syncing category product counts...');
    const categories = await Category.find();
    for (const cat of categories) {
      const count = await Product.countDocuments({ category: cat.name });
      cat.productCount = count;
      await cat.save();
    }

    const counts = {
      banners: await Banner.countDocuments(),
      categories: await Category.countDocuments(),
      industries: await Industry.countDocuments(),
      downloads: await DownloadResource.countDocuments(),
      products: await Product.countDocuments(),
    };

    console.log('[Seed] Database populated successfully! Summary:', counts);
    process.exit(0);
  } catch (error) {
    console.error(`[Seed] Error during seeding: ${error.message}`);
    process.exit(1);
  }
}

seedData();
